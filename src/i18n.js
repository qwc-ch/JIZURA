/* 部件名标签：按语言运行时改写 J.*.name（与旧版 build 注入的 english.js 等相同机制） */
import { J } from './engine.js';
import { NAMES } from './labels/names.js';

const LABEL_MODS = {
  'zh-Hans': () => import('./labels/zh-hans.js'),
  'zh-Hant': () => import('./labels/zh-hant.js'),
  en: () => import('./labels/en.js'),
  ko: () => import('./labels/ko.js'),
};
function applyNames(lang) {
  const N = NAMES[lang];
  if (!N) return;
  for (const [k, [n, d]] of Object.entries(N.styles || {})) {
    if (J.STYLES[k]) { J.STYLES[k].name = n; if (d) J.STYLES[k].desc = d; }
  }
  for (const [k, n] of Object.entries(N.moods || {})) if (J.MOODS[k]) J.MOODS[k].name = n;
}
export async function applyUiLabels(lang) {
  setTLang(lang);
  applyNames(lang);
  if (lang === 'ja') return;
  const m = LABEL_MODS[lang];
  if (!m) return;
  try { await m(); } catch (e) { console.warn('label module failed', e); }
}
